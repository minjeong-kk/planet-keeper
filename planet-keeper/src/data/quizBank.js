// ── review 접근 헬퍼 ─────────────────────────────────────────────
// 해설은 review(블록 배열) 하나만이 원본이다. 예전에는 explanation 문자열을 따로
// 들고 있었는데, 같은 내용을 두 군데 적어두면 한쪽만 고쳤을 때 화면과 저장본의
// 해설이 어긋난다. 평문이 필요한 곳(quizLog에 남기는 기록)은 여기서 만들어 쓴다.
const ALL_QUESTIONS = [...STAGE3_QUESTIONS, ...STAGE4_QUESTIONS];

/** 문제 id로 해설 블록을 찾는다. quizLog에는 id만 남아 있어도 해설을 되살릴 수 있다. */
export const reviewOf = (id) => ALL_QUESTIONS.find((q) => q.id === id)?.review ?? null;

/** 해설 블록을 한 덩어리 평문으로 펼친다(저장 기록용 - 화면은 블록을 그대로 그린다). */
export function reviewToText(review) {
  if (!review?.length) return "";
  const parts = [];
  for (const b of review) {
    if (b.text) parts.push(b.text);
    if (b.paragraphs) parts.push(...b.paragraphs);
    if (b.steps) parts.push(b.steps.map((s) => s.text).join(" → "));
    if (b.items) parts.push(...b.items.map((i) => `${i.label}: ${i.text}`));
    if (b.lines) parts.push(...b.lines);
    if (b.vars) parts.push(...b.vars.map((v) => `${v.sym} = ${v.text}`));
  }
  return parts.join(" ");
}
